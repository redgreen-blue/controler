/**
 * Embed main/index.html as a C string literal.
 *
 * Usage:
 *   node scripts/embed-html-to-c.js
 *
 * Reads  main/index.html
 * Writes main/index_html.h
 */

import { readFileSync, writeFileSync } from 'fs';
import { resolve, dirname } from 'path';
import { fileURLToPath } from 'url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = dirname(__filename);

const projectRoot = resolve(__dirname, '..', '..');
const inputPath = resolve(projectRoot, 'main', 'index.html');
const outputPath = resolve(projectRoot, 'main', 'index_html.h');

const htmlContent = readFileSync(inputPath, 'utf-8');

function escapeForCString(input) {
  return input
    .replace(/\\/g, '\\\\')
    .replace(/"/g, '\\"')
    .replace(/\n/g, '\\n"\n"')
    .replace(/\r/g, '\\r')
    .replace(/\t/g, '\\t');
}

const escaped = escapeForCString(htmlContent);

const header = `/*
 * Auto-generated by web/scripts/embed-html-to-c.js
 * Do not edit manually.
 */

#ifndef INDEX_HTML_H
#define INDEX_HTML_H

static const char index_html[] =
"${escaped}";

#endif /* INDEX_HTML_H */
`;

writeFileSync(outputPath, header, 'utf-8');
console.log(`Embedded ${inputPath} -> ${outputPath}`);
console.log(`Original size: ${htmlContent.length} bytes`);
